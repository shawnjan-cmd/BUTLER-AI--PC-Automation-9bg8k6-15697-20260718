import shutil
from pathlib import Path
root = Path.home() / 'Projects'
if not root.exists(): root = Path.home()
print(f'Scanning {root}...')
total = 0; count = 0
for nm in root.rglob('node_modules'):
    if not nm.is_dir(): continue
    try:
        sz = sum(f.stat().st_size for f in nm.rglob('*') if f.is_file())
        shutil.rmtree(nm, ignore_errors=True)
        total += sz; count += 1
        print(f'  removed {nm} ({sz/1024/1024:.1f} MB)')
    except Exception as e:
        print(f'  skip {nm}: {e}')
print(f'\n[DONE] Removed {count} node_modules ({total/1024/1024/1024:.2f} GB freed)')