export default function SecurityShowcase({ mode = 'full' }: { mode?: 'full' | 'strip' }) {
  const router = useRouter();
  const [idx, setIdx] = useState(0);
  const timer = useRef<ReturnType<typeof setInterval> | null>(null);

  useEffect(() => {
    timer.current = setInterval(
      () => setIdx(i => (i + 1) % Math.max(SECURITY_FACTS.length, 1)),
      4000,
    );
    return () => { if (timer.current) clearInterval(timer.current); };
  }, []);

  const fact = SECURITY_FACTS[idx] ?? SECURITY_FACTS[0];
  const open = useCallback(() => {
    haptics.selection();
    if (fact?.route) {
      try { router.push(fact.route as any); } catch {}
    }
  }, [fact, router]);

  if (!fact) return null;

  if (mode === 'strip') {
    return (
      <TouchableOpacity onPress={open} activeOpacity={0.8} style={s.strip}>
        <TinyMark size={9} color={fact.color} />
        <Text numberOfLines={1} style={[s.stripLabel, { color: fact.color }]}>{fact.label}</Text>
        <Text numberOfLines={1} style={s.stripDetail}>{fact.detail}</Text>
        <Text style={s.stripCount}>
          {String(idx + 1).padStart(2, '0')}/{SECURITY_FACTS.length}
        </Text>
      </TouchableOpacity>
    );
  }

  return (
    <View>
      {/* progress dots */}
      <View style={s.dotsRow}>
        <View style={{ flexDirection: 'row', gap: 4 }}>
          {SECURITY_FACTS.map((_, i) => (
            <View key={i} style={[s.dot, i === idx && { width: 14, backgroundColor: fact.color }]} />
          ))}
        </View>
        <View style={{ flexDirection: 'row', alignItems: 'center', gap: 4 }}>
          <Text style={s.tapText}>TAP FOR DETAILS</Text>
          <TinyMark size={8} color={C.dim} />
        </View>
      </View>

      {/* rotating fact card */}
      <TouchableOpacity onPress={open} activeOpacity={0.85}
        style={[s.factCard, { borderColor: fact.color + '55' }]}>
        <CornerGlyph color={fact.color} corner="tr" inset={7} />
        <View style={[s.factIcon, { borderColor: fact.color + '55' }]}>
          <MaterialCommunityIcons name={fact.mcIcon as any} size={20} color={fact.color} />
        </View>
        <View style={{ flex: 1 }}>
          <View style={{ flexDirection: 'row', alignItems: 'center', gap: 6 }}>
            <View style={[s.liveDot, { backgroundColor: fact.color }]} />
            <Text style={[s.factLabel, { color: fact.color }]}>{fact.label}</Text>
            <View style={s.verified}>
              <Text style={s.verifiedText}>✓ VERIFIED</Text>
            </View>
          </View>
          <Text numberOfLines={2} style={s.factDetail}>{fact.detail}</Text>
        </View>
        <View style={s.counter}>
          <Text style={s.counterBig}>{String(idx + 1).padStart(2, '0')}</Text>
          <Text style={s.counterSmall}>/{SECURITY_FACTS.length}</Text>
        </View>
      </TouchableOpacity>

      {/* 6-tile stat grid */}
      <View style={s.grid}>
        {STAT_TILES.map(t => (
          <View key={t.small} style={[s.tile, { borderColor: t.color + '45' }]}>
            <CornerGlyph color={t.color} corner="tr" inset={6} />
            <t.Icon name={t.name as any} size={18} color={t.color} />
            <Text style={[s.tileBig, { color: t.color }]}>{t.big}</Text>
            <Text style={s.tileSmall}>{t.small}</Text>
          </View>
        ))}
      </View>

      <FootNote>
        {`rotates every 4s · ${SECURITY_FACTS.length} verifiable guarantees · tap any card to jump to its source screen`}
      </FootNote>
    </View>
  );
}

