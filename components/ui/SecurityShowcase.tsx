// MicroGlyph removed — it statically imports react-native-svg which crashes Android boot.
// Replaced with pure View-based decorative marks (zero native dependencies).
function TinyMark({ size = 8, color = '#5A6880', style }: { size?: number; color?: string; style?: any }) {
  return (
    <View style={[{ width: size, height: size, borderRadius: 2, borderWidth: 1, borderColor: color, opacity: 0.55 }, style]}
      pointerEvents="none" />
  );
}
function CornerGlyph({ color, corner = 'tr', inset = 8 }: { color: string; corner?: 'tl'|'tr'|'bl'|'br'; inset?: number }) {
  const pos: any = { position: 'absolute' };
  if (corner.includes('t')) pos.top = inset; else pos.bottom = inset;
  if (corner.includes('r')) pos.right = inset; else pos.left = inset;
  return <TinyMark color={color} size={7} style={pos} />;
}
