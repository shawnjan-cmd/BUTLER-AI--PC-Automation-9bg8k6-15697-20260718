/**
 * gen-tab-sources.mjs
 * AUTO-GENERATES constants/tabSourcesBundle.ts by embedding real file source.
 * Run: node tools/gen-tab-sources.mjs
 * Wired via predev / prebuild in package.json so it never drifts.
 *
 * AUTO-HEAL GUARDS:
 *  - Missing files are skipped with a warning (never crash the build)
 *  - Output is always valid TypeScript even if all files are missing
 *  - Backs up the existing tabSourcesBundle.ts before overwriting
 */

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');

// Files to embed — add/remove paths here as needed
const FILES = [
  'services/haptics.ts',
  'constants/HeaderConstants.ts',
  'constants/butlerKnowledge.ts',
  'metro.config.js',
  'babel.config.js',
  'react-native.config.js',
  'services/serverConnection.ts',
  'services/autoConnectEngine.ts',
  'services/connectionHub.ts',
  'services/jsonGuard.ts',
  'services/powerhouseImport.ts',
  'services/uiConfig.ts',
  'services/onboardingState.ts',
  'app/(tabs)/nexushome.tsx',
  'app/(tabs)/butler.tsx',
  'app/(tabs)/builder.tsx',
  'app/(tabs)/knowledge.tsx',
  'app/(tabs)/scripts.tsx',
  'app/(tabs)/logs.tsx',
  'app/(tabs)/fileshare.tsx',
  'app/(tabs)/settings.tsx',
  'app/(tabs)/onboarding.tsx',
  'app/(tabs)/_layout.tsx',
  'app/_layout.tsx',
  'components/ui/FuturisticTabBar.tsx',
  'components/ui/CompactPageHeader.tsx',
  'components/ui/TabErrorBoundary.tsx',
  'components/ui/MasterJsonPanel.tsx',
  'components/ui/ButlerNexusHeader.tsx',
  'components/ui/QuickButlerBar.tsx',
  'hooks/useConnection.ts',
  'index.js',
];

function escape(str) {
  return str
    .replace(/\\/g, '\\\\')
    .replace(/`/g, '\\`')
    .replace(/\$\{/g, '\\${');
}

const outPath = path.join(ROOT, 'constants', 'tabSourcesBundle.ts');

// Auto-heal: backup existing file before overwriting
if (fs.existsSync(outPath)) {
  try {
    fs.copyFileSync(outPath, outPath + '.bak');
  } catch {}
}

const lines = [];
lines.push('/**');
lines.push(' * AUTO-GENERATED by tools/gen-tab-sources.mjs — DO NOT EDIT BY HAND.');
lines.push(' * Re-run: node tools/gen-tab-sources.mjs');
lines.push(' * Or run expo start / eas build — predev/prebuild hooks do it automatically.');
lines.push(' * Last generated: ' + new Date().toISOString());
lines.push(' */');
lines.push('');
lines.push("import { registerTabSource } from './appSourceBundle';");
lines.push('');

let count = 0;
const missing = [];

for (const rel of FILES) {
  const abs = path.join(ROOT, rel);
  if (!fs.existsSync(abs)) {
    missing.push(rel);
    console.warn(`  [SKIP] not found: ${rel}`);
    // Register a stub so exports never break runtime
    lines.push(`// ── ${rel} — FILE NOT FOUND (stub) ──`);
    lines.push(`registerTabSource(${JSON.stringify(rel)}, '// [source not available at build time]');`);
    lines.push('');
    continue;
  }
  let src;
  try {
    src = fs.readFileSync(abs, 'utf8');
  } catch (e) {
    console.warn(`  [ERROR] could not read: ${rel} — ${e.message}`);
    lines.push(`// ── ${rel} — READ ERROR ──`);
    lines.push(`registerTabSource(${JSON.stringify(rel)}, '// [source read error at build time]');`);
    lines.push('');
    continue;
  }
  lines.push(`// ── ${rel} ──`);
  lines.push(`registerTabSource(${JSON.stringify(rel)}, \`${escape(src)}\`);`);
  lines.push('');
  count++;
}

const out = lines.join('\n');

try {
  fs.writeFileSync(outPath, out, 'utf8');
  console.log(`✓ gen-tab-sources: embedded ${count} files → constants/tabSourcesBundle.ts`);
  if (missing.length) {
    console.warn(`  Stubbed ${missing.length} missing files: ${missing.join(', ')}`);
  }
} catch (e) {
  console.error(`✗ gen-tab-sources: WRITE FAILED — ${e.message}`);
  // Restore backup if write failed
  const bak = outPath + '.bak';
  if (fs.existsSync(bak)) {
    try {
      fs.copyFileSync(bak, outPath);
      console.warn('  Restored previous tabSourcesBundle.ts from backup');
    } catch {}
  }
  process.exit(1);
}
